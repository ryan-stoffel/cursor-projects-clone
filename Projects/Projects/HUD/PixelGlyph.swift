struct PixelIconView: View {
    var glyph: PixelGlyph
    var color: Color
    var pixel: CGFloat = 2

    var body: some View {
        let rows = glyph.rows
        let width = CGFloat(rows.first?.count ?? 12) * pixel
        let height = CGFloat(rows.count) * pixel
        Canvas { ctx, _ in
            for (y, row) in rows.enumerated() {
                for (x, ch) in row.enumerated() where ch == "#" {
                    let rect = CGRect(
                        x: CGFloat(x) * pixel,
                        y: CGFloat(y) * pixel,
                        width: pixel,
                        height: pixel
                    )
                    ctx.fill(Path(rect), with: .color(color))
                }
            }
        }
        .frame(width: width, height: height)
        .accessibilityLabel(glyph.rawValue)
    }
}
